#!/usr/bin/env python3
# Carapace — build-time string encryption codegen (Slice F).
#
# Closes the gap the harness previously labelled "roadmap": the audit scores
# plaintext-string density, and the identity transform only decoys *internal*
# strings — this encrypts strings that are actually USED at runtime so they are
# absent from a static `strings` / rea `list_strings` view but correct in-process.
#
# Reads a manifest {ID: "plaintext", ...} and emits a C header of byte tables for
# the runtime loader (carapace_strings.c) to decode on demand. The dev tree keeps
# the manifest (clear); the shipped binary carries only ciphertext.
#
# Cipher: a position-dependent xorshift32 keystream XOR (NOT a single-byte XOR,
# which `strings`/entropy triage would see through). Encrypt here, decode in C —
# both sides run the identical keystream; the round-trip is proven in
# ../verify/test_slice_f.sh.
#
# HONEST TIER (CLAUDE.md §3): Speed-bump→Meaningful. NAMED BYPASS: the key is
# embedded in the binary, so an attacker recovers plaintext at rest (re-run the
# keystream) or lifts the decoded string from memory at runtime (Frida/GDB). This
# raises cost against static/one-shot AI analysis; it is NOT a secret store — a
# secret that truly can't leak belongs server-side (the only Strong tier).

import os
import sys
import json
import argparse

DEFAULT_KEY = 0x5BD1E995


def _seed(key, i):
    s = (key ^ ((i * 0x9E3779B1) & 0xFFFFFFFF)) & 0xFFFFFFFF
    return s if s != 0 else 0x1


def keystream(seed, n):
    """xorshift32 keystream — byte-identical to the C loader."""
    s = seed & 0xFFFFFFFF
    out = bytearray()
    for _ in range(n):
        s ^= (s << 13) & 0xFFFFFFFF
        s ^= (s >> 17)
        s ^= (s << 5) & 0xFFFFFFFF
        s &= 0xFFFFFFFF
        out.append(s & 0xFF)
    return out


def encrypt(plain: bytes, key: int, i: int) -> bytes:
    ks = keystream(_seed(key, i), len(plain))
    return bytes(p ^ k for p, k in zip(plain, ks))


def _carr(name, data):
    body = ", ".join("0x%02x" % b for b in data) or "0"
    return f"static const unsigned char {name}[] = {{ {body} }};"


def generate(manifest, mode, key):
    ids = list(manifest.keys())
    lines = []
    lines.append("#ifndef CARAPACE_STRINGS_GEN_H")
    lines.append("#define CARAPACE_STRINGS_GEN_H")
    lines.append(f"/* GENERATED by carapace_string_encrypt.py — do not edit. mode={mode} */")
    lines.append("enum {")
    for i, k in enumerate(ids):
        lines.append(f"    CSTR_{k} = {i},")
    lines.append(f"    CARAPACE_ENC_COUNT = {len(ids)}")
    lines.append("};")
    lines.append(f"#define CARAPACE_STR_KEY 0x{key:08x}u")
    if mode == "enc":
        lines.append("#define CARAPACE_STRINGS_ENCRYPTED 1")
    lines.append("")
    lines.append("#ifdef CARAPACE_STRINGS_IMPL")
    tbl = []
    for i, k in enumerate(ids):
        plain = manifest[k].encode("utf-8")
        data = encrypt(plain, key, i) if mode == "enc" else plain
        lines.append(_carr(f"carapace_enc_{i}", data))
        tbl.append(f"    {{ carapace_enc_{i}, {len(data)} }}")
    lines.append("static const struct { const unsigned char *d; unsigned n; }")
    lines.append("carapace_enc_table[CARAPACE_ENC_COUNT] = {")
    lines.append(",\n".join(tbl))
    lines.append("};")
    if mode == "enc":
        # audit marker symbol (a name, not a plaintext tell) => "strings encrypted?"
        lines.append("const unsigned char carapace_strings_enc = 1;")
    lines.append("#endif /* CARAPACE_STRINGS_IMPL */")
    lines.append("#endif /* CARAPACE_STRINGS_GEN_H */")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description="Carapace build-time string encryption codegen.")
    sub = ap.add_subparsers(dest="cmd", required=True)
    g = sub.add_parser("gen", help="generate the C header from a manifest")
    g.add_argument("--manifest", required=True, help="JSON {ID: plaintext}")
    g.add_argument("--mode", choices=["enc", "plain"], default="enc")
    g.add_argument("--key", type=lambda x: int(x, 0), default=DEFAULT_KEY)
    g.add_argument("--out", required=True)
    args = ap.parse_args(argv)

    if args.cmd == "gen":
        with open(args.manifest) as fh:
            manifest = json.load(fh)
        if not isinstance(manifest, dict) or not manifest:
            print("manifest must be a non-empty {ID: plaintext} object", file=sys.stderr)
            return 2
        header = generate(manifest, args.mode, args.key)
        with open(args.out, "w") as fh:
            fh.write(header)
        print(f"mode {args.mode}: wrote {len(manifest)} strings -> {args.out}")
        return 0


if __name__ == "__main__":
    sys.exit(main())
